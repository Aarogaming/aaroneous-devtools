use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

#[derive(Deserialize, Serialize, Debug, Clone)]
struct DigestRecord {
    schema_version: u32,
    artifact_kind: String,
    job_id: String,
    submitted_at_secs: u64,
    outcome: String,
    input: String,
    proposal: Option<DigestDraft>,
    error: Option<String>,
}

#[derive(Deserialize, Serialize, Debug, Clone)]
struct DigestDraft {
    task: String,
    observations: Vec<String>,
    risks: Vec<String>,
    test_plan: Vec<String>,
    recommended_next_step: String,
    rust_draft: Option<String>,
}

/// Pure helper to extract milestone ID (e.g. "M1") from a job ID like "PORTFOLIO-M1".
pub fn extract_milestone_id(job_id: &str) -> &str {
    let upper = job_id;
    if let Some(pos) = upper.rfind('-') {
        let prefix = &upper[..pos];
        if prefix.eq_ignore_ascii_case("PORTFOLIO") {
            return &upper[pos + 1..];
        }
    }
    job_id
}

/// Milestone sort key for natural ordering (e.g. M1 < M2 < M10).
fn milestone_sort_key(id: &str) -> (u32, String) {
    let trimmed = id.trim();
    if let Some(rest) = trimmed
        .strip_prefix('M')
        .or_else(|| trimmed.strip_prefix('m'))
    {
        if let Ok(num) = rest.parse::<u32>() {
            return (num, String::new());
        }
    }
    (u32::MAX, trimmed.to_string())
}

/// Escape markdown table cell content.
fn escape_table_cell(text: &str) -> String {
    text.replace('|', "\\|").replace(['\r', '\n'], " ")
}

/// Scans `results_dir` (and optionally `archive_dir`) for `PORTFOLIO-*` results
/// and produces a unified markdown digest at `output_path`.
pub fn generate_digest(
    results_dir: &Path,
    archive_dir: Option<&Path>,
    output_path: &Path,
) -> Result<usize> {
    if !results_dir.is_absolute() {
        bail!(
            "results_dir must be an absolute path: {}",
            results_dir.display()
        );
    }
    if !output_path.is_absolute() {
        bail!(
            "output_path must be an absolute path: {}",
            output_path.display()
        );
    }

    let mut candidate_paths = Vec::new();
    if let Ok(entries) = fs::read_dir(results_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|s| s.to_str()) == Some("json") {
                candidate_paths.push(path);
            }
        }
    }
    if let Some(arch) = archive_dir {
        if let Ok(entries) = fs::read_dir(arch) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().and_then(|s| s.to_str()) == Some("json") {
                    candidate_paths.push(path);
                }
            }
        }
    }

    let mut latest_by_milestone: BTreeMap<String, (u64, DigestRecord)> = BTreeMap::new();

    for path in candidate_paths {
        let name = path.file_name().and_then(|s| s.to_str()).unwrap_or("");
        if !name.to_ascii_uppercase().starts_with("PORTFOLIO-") {
            continue;
        }
        if let Ok(text) = fs::read_to_string(&path) {
            if let Ok(rec) = serde_json::from_str::<DigestRecord>(&text) {
                let milestone = extract_milestone_id(&rec.job_id).to_uppercase();
                let entry = latest_by_milestone
                    .entry(milestone)
                    .or_insert((0, rec.clone()));
                if rec.submitted_at_secs >= entry.0 {
                    *entry = (rec.submitted_at_secs, rec);
                }
            }
        }
    }

    let mut items: Vec<_> = latest_by_milestone.into_values().map(|(_, r)| r).collect();
    items.sort_by(|a, b| {
        let id_a = extract_milestone_id(&a.job_id);
        let id_b = extract_milestone_id(&b.job_id);
        milestone_sort_key(id_a).cmp(&milestone_sort_key(id_b))
    });

    let mut md = String::new();
    md.push_str("# Portfolio Triage Digest\n\n");
    md.push_str("> **STATUS**: AUTOMATED LOCAL-MODEL ANALYSIS SYNTHESIS\n");
    md.push_str("> **PURPOSE**: Structured triage & speculative approach proposals generated by local GPU model (`qwen3.5:9b-q6`) to assist cloud agents and human contributors in scoping and executing roadmap work.\n");
    md.push_str("> **GOVERNANCE NOTICE**: These proposals are strictly advisory drafts (`pending-owner-review`). They do NOT claim coordination queue rows, authorize production code writes, or modify architecture invariants.\n\n");

    if items.is_empty() {
        md.push_str("## Current Status\n\n");
        md.push_str("No portfolio triage records have completed yet. Analysis packets have been generated in `worker-jobs/` and are actively queued for background execution by the local worker.\n");
    } else {
        md.push_str("## Executive Portfolio Matrix\n\n");
        md.push_str("| Milestone | Task Summary | Recommended Approach | Key Risks | Status |\n");
        md.push_str("| :--- | :--- | :--- | :--- | :--- |\n");

        for item in &items {
            let m_id = extract_milestone_id(&item.job_id);
            let (task, approach, risks) = if let Some(ref p) = item.proposal {
                let first_risk = p
                    .risks
                    .first()
                    .cloned()
                    .unwrap_or_else(|| "None stated".into());
                (
                    escape_table_cell(&p.task),
                    escape_table_cell(&p.recommended_next_step),
                    escape_table_cell(&first_risk),
                )
            } else if let Some(ref err) = item.error {
                (
                    "Error during analysis".into(),
                    escape_table_cell(err),
                    "Model generation failed".into(),
                )
            } else {
                ("Pending proposal".into(), "N/A".into(), "N/A".into())
            };

            md.push_str(&format!(
                "| **{}** | {} | {} | {} | `{}` |\n",
                m_id, task, approach, risks, item.outcome
            ));
        }

        md.push_str("\n---\n\n## Detailed Milestone Assessments\n\n");

        for item in &items {
            let m_id = extract_milestone_id(&item.job_id);
            md.push_str(&format!("### Milestone {}\n\n", m_id));
            md.push_str(&format!("- **Job ID**: `{}`\n", item.job_id));
            md.push_str(&format!("- **Review Outcome**: `{}`\n", item.outcome));
            md.push_str(&format!(
                "- **Submitted**: unix timestamp `{}`\n",
                item.submitted_at_secs
            ));

            if let Some(ref p) = item.proposal {
                md.push_str(&format!("\n#### Task Formulation\n{}\n", p.task.trim()));
                md.push_str(&format!(
                    "\n#### Recommended Approach\n{}\n",
                    p.recommended_next_step.trim()
                ));

                if !p.observations.is_empty() {
                    md.push_str("\n#### Observations\n");
                    for obs in &p.observations {
                        md.push_str(&format!("- {}\n", obs.trim()));
                    }
                }

                if !p.risks.is_empty() {
                    md.push_str("\n#### Identified Risks\n");
                    for risk in &p.risks {
                        md.push_str(&format!("- {}\n", risk.trim()));
                    }
                }

                if !p.test_plan.is_empty() {
                    md.push_str("\n#### Proposed Test Plan\n");
                    for test in &p.test_plan {
                        md.push_str(&format!("- {}\n", test.trim()));
                    }
                }

                if let Some(ref code) = p.rust_draft {
                    if !code.trim().is_empty() {
                        md.push_str("\n#### Speculative Rust Draft\n```rust\n");
                        md.push_str(code.trim());
                        md.push_str("\n```\n");
                    }
                }
            } else if let Some(ref err) = item.error {
                md.push_str(&format!("\n#### Error Encountered\n```\n{}\n```\n", err));
            }

            md.push_str("\n---\n\n");
        }
    }

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }

    let staging = output_path.with_extension("partial");
    fs::write(&staging, md.as_bytes())?;
    fs::rename(&staging, output_path)?;

    Ok(items.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_extract_milestone_id() {
        assert_eq!(extract_milestone_id("PORTFOLIO-M1"), "M1");
        assert_eq!(extract_milestone_id("PORTFOLIO-M58"), "M58");
        assert_eq!(extract_milestone_id("portfolio-m10"), "m10");
        assert_eq!(extract_milestone_id("OTHER-JOB"), "OTHER-JOB");
    }

    #[test]
    fn test_milestone_sort_key() {
        assert_eq!(milestone_sort_key("M1"), (1, String::new()));
        assert_eq!(milestone_sort_key("M8"), (8, String::new()));
        assert_eq!(milestone_sort_key("M10"), (10, String::new()));
        assert_eq!(milestone_sort_key("m59"), (59, String::new()));
        assert!(milestone_sort_key("M2") < milestone_sort_key("M10"));
    }

    #[test]
    fn test_generate_digest_empty_directory() {
        let temp = tempfile::tempdir().expect("tempdir");
        let results_dir = temp.path().join("results");
        let output = temp.path().join("PORTFOLIO_TRIAGE_DIGEST.md");
        fs::create_dir_all(&results_dir).expect("results dir");

        let count = generate_digest(&results_dir, None, &output).expect("digest");
        assert_eq!(count, 0);
        let content = fs::read_to_string(&output).expect("read digest");
        assert!(content.contains("# Portfolio Triage Digest"));
        assert!(content.contains("No portfolio triage records have completed yet"));
    }

    #[test]
    fn test_generate_digest_with_records() {
        let temp = tempfile::tempdir().expect("tempdir");
        let results_dir = temp.path().join("results");
        let archive_dir = temp.path().join("archive");
        let output = temp.path().join("PORTFOLIO_TRIAGE_DIGEST.md");
        fs::create_dir_all(&results_dir).expect("results dir");
        fs::create_dir_all(&archive_dir).expect("archive dir");

        let rec_m1 = DigestRecord {
            schema_version: 1,
            artifact_kind: "foundation.local-worker-result".into(),
            job_id: "PORTFOLIO-M1".into(),
            submitted_at_secs: 100,
            outcome: "pending-owner-review".into(),
            input: "test input".into(),
            proposal: Some(DigestDraft {
                task: "Converge active integration branch".into(),
                observations: vec!["CI result pending".into()],
                risks: vec!["Merge conflicts in scheduler".into()],
                test_plan: vec!["cargo test".into()],
                recommended_next_step: "Run rebase on main".into(),
                rust_draft: None,
            }),
            error: None,
        };

        let rec_m8 = DigestRecord {
            schema_version: 1,
            artifact_kind: "foundation.local-worker-result".into(),
            job_id: "PORTFOLIO-M8".into(),
            submitted_at_secs: 110,
            outcome: "pending-owner-review".into(),
            input: "test input".into(),
            proposal: Some(DigestDraft {
                task: "Bounded reducer reference path".into(),
                observations: vec!["Zero-alloc required".into()],
                risks: vec!["Stack bounds".into()],
                test_plan: vec!["ast_auditor".into()],
                recommended_next_step: "Synthesize reducer trait".into(),
                rust_draft: None,
            }),
            error: None,
        };

        fs::write(
            results_dir.join("PORTFOLIO-M1-0000.json"),
            serde_json::to_string(&rec_m1).unwrap(),
        )
        .unwrap();

        fs::write(
            archive_dir.join("PORTFOLIO-M8-0000.json"),
            serde_json::to_string(&rec_m8).unwrap(),
        )
        .unwrap();

        let count = generate_digest(&results_dir, Some(&archive_dir), &output).expect("digest");
        assert_eq!(count, 2);

        let content = fs::read_to_string(&output).expect("read digest");
        assert!(content.contains("| **M1** |"));
        assert!(content.contains("| **M8** |"));
        assert!(content.contains("Converge active integration branch"));
        assert!(content.contains("Bounded reducer reference path"));
        assert!(content.contains("Run rebase on main"));
        assert!(content.contains("Synthesize reducer trait"));
    }
}
